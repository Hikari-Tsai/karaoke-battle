// Tiny string table: zh-TW primary, English fallback. No ARB generation.
import 'package:flutter/foundation.dart';

/// 'zh' (default) or 'en'. Changing it rebuilds listeners of [I18n.notifier].
class I18n {
  I18n._();
  static final ValueNotifier<String> notifier = ValueNotifier('zh');
  static String get lang => notifier.value;
  static set lang(String v) => notifier.value = v;
}

/// Looks up [key] in the table; returns the zh-TW string by default, English
/// when `I18n.lang == 'en'`, and the key itself when missing.
String tr(String key, [Map<String, Object?>? args]) {
  final e = _table[key];
  var s = e == null ? key : (I18n.lang == 'en' ? e.$2 : e.$1);
  if (args != null) {
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  }
  return s;
}

