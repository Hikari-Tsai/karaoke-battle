/// [genre] (as the charts give it, in English) in [lang] ('zh', 'en', 'ja').
String genreName(String genre, String lang) {
  final n = _names[genre];
  if (n == null) return genre;
  return switch (lang) {
    'zh' => n.$1,
    'ja' => n.$2,
    _ => genre,
  };
}
